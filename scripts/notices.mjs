// Writes THIRD_PARTY_NOTICES.md: everything this repository and its apps use from others, with
// licenses and source links. Run from the repo root after dependency or example changes:
//   node scripts/notices.mjs
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const json = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const catalog = json("studio/src/catalog/catalog.json").entries;
const reference = json("studio/src/catalog/index-opensource.json").entries;
const examples = readdirSync(join(root, "examples"))
  .filter((d) => existsSync(join(root, "examples", d, "example.json")))
  .map((slug) => ({ slug, ...json(`examples/${slug}/example.json`) }))
  .sort((a, b) => a.order - b.order);

const repoUrl = (repo) => {
  const url = typeof repo === "string" ? repo : repo?.url;
  if (!url) return null;
  const m = url.match(/github\.com[/:]([^/]+\/[^/#?]+?)(?:\.git)?(?:[/#?]|$)/);
  return m ? `https://github.com/${m[1]}` : url.replace(/^git\+/, "").replace(/\.git$/, "");
};
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|");

/** Production dependencies of an npm project, from its installed node_modules. */
function npmDeps(dir) {
  const lock = json(join(dir, "package-lock.json"));
  return Object.entries(lock.packages)
    .filter(([path, p]) => path.startsWith("node_modules/") && !p.dev && !p.devOptional)
    .map(([path, p]) => {
      const name = path.slice(path.lastIndexOf("node_modules/") + 13);
      const manifest = join(root, dir, path, "package.json");
      const meta = existsSync(manifest) ? JSON.parse(readFileSync(manifest, "utf8")) : {};
      return { name, version: p.version, license: p.license ?? meta.license ?? "see package", url: repoUrl(meta.repository) ?? `https://www.npmjs.com/package/${name}` };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

/** The hub's Python packages with their license metadata (from its uv environment). */
function pythonDeps() {
  const code = `import importlib.metadata as m, json
out = []
for d in m.distributions():
    md = d.metadata
    urls = [u.split(",", 1)[-1].strip() for u in (md.get_all("Project-URL") or [])]
    gh = next((u for u in urls if "github.com" in u), None) or md.get("Home-page")
    lic = md.get("License-Expression") or (md.get("License") if md.get("License") and len(md.get("License")) < 60 else None)
    if not lic:
        lic = next((c.split("::")[-1].strip() for c in (md.get_all("Classifier") or []) if c.startswith("License ::")), "see package")
    out.append({"name": md["Name"], "version": d.version, "license": lic, "url": gh or f"https://pypi.org/project/{md['Name']}/"})
print(json.dumps(out))`;
  try {
    const uv = existsSync(join(root, "desktop/vendor/bin/uv")) ? join(root, "desktop/vendor/bin/uv") : "uv";
    const out = execFileSync(uv, ["run", "--frozen", "--no-dev", "python", "-c", code], { cwd: join(root, "hub"), encoding: "utf8" });
    return JSON.parse(out)
      .filter((d) => d.name.toLowerCase() !== "siljangnim-hub")
      .sort((a, b) => a.name.localeCompare(b.name));
  } catch (err) {
    console.warn(`[notices] Python dependencies skipped: ${err.message}`);
    return [];
  }
}

